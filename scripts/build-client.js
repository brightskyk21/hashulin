const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const source = path.join(root, 'src/client');
const output = path.join(root, 'public/v2');

function readSource(file) {
  const resolved = path.resolve(source, file);
  if (!resolved.startsWith(source + path.sep)) throw new Error(`Invalid source path: ${file}`);
  return fs.readFileSync(resolved, 'utf8');
}

function bundle(manifest, separator) {
  const entries = JSON.parse(readSource(manifest));
  if (new Set(entries).size !== entries.length) throw new Error(`Duplicate entry in ${manifest}`);
  return entries.map((file) => `/* Source: ${file} */\n${readSource(file)}`).join(separator);
}

function includeHtml(file, parents = []) {
  if (parents.includes(file)) throw new Error(`Circular HTML include: ${file}`);
  return readSource(file).replace(/<!--\s*include:\s*([\w./-]+)\s*-->/g, (_, child) =>
    includeHtml(child, [...parents, file]),
  );
}

function buildClient({ check = false } = {}) {
  const generated = {
    'app.js':
      '// Generated by npm run build. Edit src/client instead.\n' + bundle('scripts.json', '\n;\n'),
    'app.css':
      '/* Generated by npm run build. Edit src/client instead. */\n' + bundle('styles.json', '\n'),
    'index.html':
      '<!-- Generated by npm run build. Edit src/client instead. -->\n' + includeHtml('index.html'),
  };
  const stale = [];
  for (const [name, content] of Object.entries(generated)) {
    const file = path.join(output, name);
    if (check) {
      if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== content) stale.push(name);
    } else {
      fs.mkdirSync(output, { recursive: true });
      fs.writeFileSync(file, content);
    }
  }
  if (stale.length) throw new Error(`Run npm run build to update: ${stale.join(', ')}`);
  return generated;
}

if (require.main === module) {
  buildClient({ check: process.argv.includes('--check') });
  console.log(
    process.argv.includes('--check') ? 'Client assets are up to date.' : 'Client assets built.',
  );
}

module.exports = { buildClient };
